#!/bin/sh
# Regenerates licenses/rust.md, the licences of the Rust libraries built into
# P12 Librarian and the p12 tool. Run by `npm run tauri build` before the
# frontend is built; licenses/javascript.md is written by the frontend build.
# Needs cargo-about: cargo install --locked cargo-about --features cli
set -e
cd "$(dirname "$0")/.."
{
  echo "# Licences of the Rust libraries in P12 Librarian"
  echo
  echo "Generated by licenses/generate.sh with cargo-about. Do not edit."
  echo
  cargo about generate -c licenses/about.toml --workspace licenses/about.hbs
} > licenses/rust.md.tmp
mv licenses/rust.md.tmp licenses/rust.md
echo "Wrote licenses/rust.md"
